#!/usr/bin/env bash
# Cloud Agent start phase for resource-allocation-planner.
# Brings up the Supabase local stack (Docker) and refreshes local dev secrets.
# Idempotent and best-effort: a Supabase hiccup must not block the web app,
# which still runs in guest mode against the placeholder .env.local.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
log() { echo "[start] $*"; }

# --- Docker daemon (required by the Supabase local stack) --------------------
# Nested Docker in the Cloud Agent VM needs:
#   * fuse-overlayfs storage driver (native overlay2 is unavailable), and
#   * the legacy iptables backend (the nftables backend silently drops
#     inter-container traffic here, so Postgres becomes unreachable).
sudo update-alternatives --set iptables /usr/sbin/iptables-legacy   >/dev/null 2>&1 || true
sudo update-alternatives --set ip6tables /usr/sbin/ip6tables-legacy >/dev/null 2>&1 || true

if ! docker info >/dev/null 2>&1; then
  log "starting dockerd (fuse-overlayfs)"
  sudo bash -c 'nohup dockerd --storage-driver=fuse-overlayfs >/tmp/dockerd.log 2>&1 &'
  for _ in $(seq 1 30); do docker info >/dev/null 2>&1 && break; sleep 1; done
fi
sudo chmod 666 /var/run/docker.sock >/dev/null 2>&1 || true

if ! docker info >/dev/null 2>&1; then
  log "dockerd unavailable; skipping Supabase (web app runs in guest mode)"
  exit 0
fi

# --- Supabase local stack ----------------------------------------------------
if ! supabase status >/dev/null 2>&1; then
  log "supabase start (this may pull images on first run)"
  if ! supabase start; then
    log "supabase start failed; see 'supabase start' output (web app runs in guest mode)"
    exit 0
  fi
fi

# --- Refresh .env.local with live keys, then seed demo users -----------------
if supabase status -o env >/tmp/sb-status.env 2>/dev/null; then
  # shellcheck disable=SC1090
  set -a; eval "$(sed 's/^/SB_/' /tmp/sb-status.env)"; set +a
  cat > .env.local <<EOF
# Local dev env (gitignored) generated by .cursor/start.sh from 'supabase status'.
PUBLIC_SUPABASE_URL=${SB_API_URL}
PUBLIC_SUPABASE_PUBLISHABLE_KEY=${SB_PUBLISHABLE_KEY}
SUPABASE_URL=${SB_API_URL}
SUPABASE_SERVICE_ROLE_KEY=${SB_SERVICE_ROLE_KEY}
SUPABASE_DB_URL=${SB_DB_URL}
SEED_PASSWORD=password123
EOF
  log "seeding demo users (admin/demo1/demo2 @rap.local)"
  pnpm seed:users || log "seed:users failed (non-fatal)"
  log "Supabase ready: API ${SB_API_URL}  Studio ${SB_STUDIO_URL}"
fi

# --- Web dev server ----------------------------------------------------------
# Launch the Vite dev server detached so the app is reachable right after boot.
# Idempotent: skip if something already listens on 5400.
if ! curl -fsS -o /dev/null "http://127.0.0.1:5400" 2>/dev/null; then
  log "starting Vite dev server on http://127.0.0.1:5400"
  nohup pnpm dev >/tmp/vite-dev.log 2>&1 &
fi

log "done"
