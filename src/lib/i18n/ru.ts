export type RuKey = keyof typeof ru;

export function t(key: RuKey, vars?: Record<string, string>): string {
  let s: string = ru[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, v);
    }
  }
  return s;
}

